package Task;
import java.util.*;

public class prepost {

	public static void main(String[] args) {

			Scanner obj=new Scanner(System.in);
			System.out.println("Enter number : ");
			int a=obj.nextInt();
			
			System.out.println("++a :"+ ++a);
			System.out.println("a++ :"+ a++);
			System.out.println("--a :"+ --a);
			System.out.println("a-- :"+ a--);
	}

}
