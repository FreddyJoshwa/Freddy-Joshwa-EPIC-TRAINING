package Task;
import java.util.*;
public class Compassignment {

	public static void main(String[] args) {

			Scanner obj=new Scanner(System.in);
			
			System.out.println("enter the number :");
			int a=obj.nextInt();
			
			a+=5;
			System.out.println("+= "+a);
			
			a-=5;
			System.out.println("-="+a);
			
			a*=5;
			System.out.println("*="+a);
			
			a/=5;
			System.out.println("/="+a);
			
			a%=5;
			System.out.println("%="+a);
	}

}
